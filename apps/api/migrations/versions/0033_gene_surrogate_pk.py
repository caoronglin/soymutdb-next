"""Restructure gene identity: surrogate PK with assembly-scoped accession.

Genes are now identified by a surrogate ``gene_pk`` bigint. The former
string primary key becomes ``accession`` with a unique constraint on
``(assembly_id, accession)`` — v4 and v5 are distinct namespaces and the
same accession must be able to coexist in both.

Child tables keep their ``gene_id`` column name but the column now holds
the surrogate key (bigint) instead of the accession string:

* transcripts              (CASCADE)
* gene_aliases             (CASCADE)
* variant_summaries        (SET NULL, nullable)
* expression_data          (CASCADE)
* gene_homologs            (CASCADE)
* gene_data_cache          (CASCADE)

Downgrade restores the legacy global ``genes.id`` primary key. It refuses
to run while duplicate accessions exist across assemblies, because the
legacy schema cannot represent them.

Revision ID: 0033
Revises: 0032
Create Date: 2026-09-08
"""

from alembic import op

revision = "0033"
down_revision = "0032"
branch_labels = None
depends_on = None

# (table, ondelete, nullable)
_CHILD_TABLES = [
    ("transcripts", "CASCADE", True),
    ("gene_aliases", "CASCADE", True),
    ("variant_summaries", "SET NULL", False),
    ("expression_data", "CASCADE", True),
    ("gene_homologs", "CASCADE", True),
    ("gene_data_cache", "CASCADE", True),
]


def upgrade() -> None:
    # 1. Surrogate identity column on genes.
    op.execute(
        "ALTER TABLE genes ADD COLUMN gene_pk BIGINT GENERATED BY DEFAULT AS IDENTITY"
    )
    op.execute(
        "UPDATE genes SET gene_pk = nextval(pg_get_serial_sequence('genes', 'gene_pk'))"
    )
    op.execute("ALTER TABLE genes ALTER COLUMN gene_pk SET NOT NULL")

    # 2. Re-point child tables from accession strings to surrogate keys.
    #    (New foreign keys are created after the genes primary key swap.)
    for table, ondelete, not_null in _CHILD_TABLES:
        op.execute(f"ALTER TABLE {table} ADD COLUMN gene_pk BIGINT")
        op.execute(
            f"UPDATE {table} c SET gene_pk = g.gene_pk "
            "FROM genes g WHERE c.gene_id = g.id"
        )
        op.execute(
            f"ALTER TABLE {table} DROP CONSTRAINT fk_{table}_gene_id_genes"
        )
        op.execute(f"ALTER TABLE {table} DROP COLUMN gene_id")
        op.execute(f"ALTER TABLE {table} RENAME COLUMN gene_pk TO gene_id")
        if not_null:
            op.execute(f"ALTER TABLE {table} ALTER COLUMN gene_id SET NOT NULL")

    # 3. Swap the genes primary key and scope the accession to assemblies.
    op.execute("ALTER TABLE genes DROP CONSTRAINT pk_genes")
    op.execute("ALTER TABLE genes RENAME COLUMN id TO accession")
    op.execute(
        "ALTER TABLE genes ADD CONSTRAINT pk_genes PRIMARY KEY (gene_pk)"
    )
    op.execute(
        "ALTER TABLE genes ADD CONSTRAINT uq_gene_assembly_accession "
        "UNIQUE (assembly_id, accession)"
    )
    op.execute("CREATE INDEX ix_gene_accession ON genes (accession)")

    # 4. Foreign keys from the child tables to the surrogate key.
    for table, ondelete, _not_null in _CHILD_TABLES:
        op.execute(
            f"ALTER TABLE {table} ADD CONSTRAINT fk_{table}_gene_id_genes "
            f"FOREIGN KEY (gene_id) REFERENCES genes (gene_pk) ON DELETE {ondelete}"
        )


def downgrade() -> None:
    # The legacy schema cannot represent the same accession in two
    # assemblies; refuse to silently collapse them.
    op.execute(
        """
        DO $$
        BEGIN
            IF EXISTS (
                SELECT 1 FROM genes GROUP BY accession HAVING count(*) > 1
            ) THEN
                RAISE EXCEPTION
                    'Cannot downgrade migration 0033: duplicate gene accessions '
                    'across assemblies exist and the legacy schema cannot '
                    'represent them';
            END IF;
        END
        $$;
        """
    )

    # 1. Detach and re-map child tables back to accession strings.
    for table, ondelete, not_null in _CHILD_TABLES:
        op.execute(
            f"ALTER TABLE {table} DROP CONSTRAINT fk_{table}_gene_id_genes"
        )
        op.execute(f"ALTER TABLE {table} ADD COLUMN gene_id_old VARCHAR(64)")
        op.execute(
            f"UPDATE {table} c SET gene_id_old = g.accession "
            "FROM genes g WHERE c.gene_id = g.gene_pk"
        )
        op.execute(f"ALTER TABLE {table} DROP COLUMN gene_id")
        op.execute(f"ALTER TABLE {table} RENAME COLUMN gene_id_old TO gene_id")
        if not_null:
            op.execute(f"ALTER TABLE {table} ALTER COLUMN gene_id SET NOT NULL")

    # 2. Restore the legacy genes primary key on the accession.
    op.execute("ALTER TABLE genes DROP CONSTRAINT pk_genes")
    op.execute(
        "ALTER TABLE genes DROP CONSTRAINT uq_gene_assembly_accession"
    )
    op.execute("DROP INDEX IF EXISTS ix_gene_accession")
    op.execute("ALTER TABLE genes RENAME COLUMN accession TO id")
    op.execute("ALTER TABLE genes ADD CONSTRAINT pk_genes PRIMARY KEY (id)")

    # 3. Re-create legacy child foreign keys against genes (id).
    for table, ondelete, not_null in _CHILD_TABLES:
        op.execute(
            f"ALTER TABLE {table} ADD CONSTRAINT fk_{table}_gene_id_genes "
            f"FOREIGN KEY (gene_id) REFERENCES genes (id) ON DELETE {ondelete}"
        )

    # 4. Drop the surrogate column last.
    op.execute("ALTER TABLE genes DROP COLUMN gene_pk")
