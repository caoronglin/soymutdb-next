/**
 * postMessage bridge between the SoyMutDB portal and the JBrowse 2 app.
 *
 * Shared contract (mirrored in apps/web/src/lib/jbrowse-bridge.ts):
 *
 *   {
 *     source: "soymutdb-browser" | "soymutdb-jbrowse",
 *     version: 1,
 *     type: "ready" | "error" | "locus-change" | "selection-change" | "init",
 *     payload: <type-specific payload>
 *   }
 *
 * Parent-origin policy: the portal embeds this app in an iframe and appends
 * `?portalOrigin=<portal origin>` to the URL. Messages from the portal are
 * accepted only when `event.origin` matches `portalOrigin`; when the param is
 * absent (standalone / shared-link use), the bridge stays inactive and the app
 * keeps its default independent behaviour. Messages are additionally checked
 * for `source` and `version`.
 *
 * Outbound messages (ready / error / locus-change) are only posted to
 * `window.parent` when the app is actually embedded (window.parent !== window),
 * so standalone tab use never talks to an opener.
 */

export const BRIDGE_SOURCE_BROWSER = "soymutdb-browser" as const;
export const BRIDGE_SOURCE_JBROWSE = "soymutdb-jbrowse" as const;
export const BRIDGE_VERSION = 1 as const;

/** Documented message types; unknown types are rejected at the bridge. */
export const BRIDGE_TYPES = ["ready", "error", "locus-change", "selection-change", "init"] as const;
export type BridgeMessageType = (typeof BRIDGE_TYPES)[number];
export function isBridgeMessageType(value: unknown): value is BridgeMessageType {
    return typeof value === "string" && (BRIDGE_TYPES as readonly string[]).includes(value);
}

export type BridgeSource =
    | typeof BRIDGE_SOURCE_BROWSER
    | typeof BRIDGE_SOURCE_JBROWSE;

/** Full message envelope shared by both apps. */
export interface BridgeEnvelope {
    source: BridgeSource;
    version: typeof BRIDGE_VERSION;
    type: string;
    payload?: unknown;
}

/** Portal -> JBrowse: apply/restore a browser session. */
export interface InitPayload {
    assembly?: string;
    locus?: string;
    /** Track IDs to display. */
    tracks?: string[];
    /** Data release tag, carried through for deep-link fidelity. */
    release?: string;
    /** Opaque session identifier generated by the portal. */
    sessionId?: string;
    /** Monotonic scope tag; an init message from an older scope is stale. */
    scopeEpoch?: number;
}

/**
 * Post an envelope to the embedding portal frame.
 * No-op when not embedded (top-level window).
 */
export function postToParent(
    envelope: Omit<BridgeEnvelope, "source" | "version"> & { source?: BridgeSource },
    parentOrigin: string,
): void {
    if (typeof window === "undefined" || window.parent === window) return;
    // Stamp canonical source/version last so a caller cannot spoof them.
    window.parent.postMessage(
        {
            ...envelope,
            source: BRIDGE_SOURCE_JBROWSE,
            version: BRIDGE_VERSION,
        },
        parentOrigin,
    );
}

/**
 * Validate an incoming message from the portal frame.
 * @returns the envelope when valid, otherwise null (caller should warn).
 */
export function parsePortalMessage(
    event: MessageEvent,
    expectedParentOrigin: string,
): BridgeEnvelope | null {
    if (
        typeof window !== "undefined" &&
        window.parent !== window &&
        event.source !== window.parent
    ) {
        console.warn("[JBrowse] Ignoring message from a non-parent window");
        return null;
    }
    if (event.origin !== expectedParentOrigin) {
        console.warn(
            `[JBrowse] Ignoring message from unexpected origin: ${event.origin} (expected ${expectedParentOrigin})`,
        );
        return null;
    }
    const msg = event.data as Partial<BridgeEnvelope> | null | undefined;
    if (!msg || typeof msg !== "object" || !isBridgeMessageType(msg.type)) {
        console.warn("[JBrowse] Ignoring malformed bridge message", event.origin);
        return null;
    }
    if (msg.source !== BRIDGE_SOURCE_BROWSER || msg.version !== BRIDGE_VERSION) {
        console.warn(
            `[JBrowse] Ignoring invalid bridge message (source=${String(msg.source)}, version=${String(msg.version)})`,
            event.origin,
        );
        return null;
    }
    return msg as BridgeEnvelope;
}
