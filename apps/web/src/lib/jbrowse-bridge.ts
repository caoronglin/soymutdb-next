/**
 * postMessage bridge between the SoyMutDB portal and the JBrowse 2 app.
 *
 * Shared contract (mirrored in apps/jbrowse/src/bridge.ts):
 *
 *   {
 *     source: "soymutdb-browser" | "soymutdb-jbrowse",
 *     version: 1,
 *     type: "ready" | "error" | "locus-change" | "selection-change" | "init",
 *     payload: <type-specific payload>
 *   }
 *
 * Message flow:
 *   - JBrowse -> Portal: "ready"        (initialisation finished, may carry {assembly, locus})
 *   - JBrowse -> Portal: "error"        ({message})
 *   - JBrowse -> Portal: "locus-change" ({assembly, locus, tracks?}) debounced ~300ms
 *   - JBrowse -> Portal: "selection-change" (optional, reserved)
 *   - Portal -> JBrowse: "init"         ({assembly, locus, tracks, release, sessionId})
 *
 * The portal only accepts messages whose event.origin matches the iframe
 * origin, whose source/version match the contract, and (when the iframe
 * reference exists) whose event.source is the iframe's contentWindow.
 */

export const BRIDGE_SOURCE_BROWSER = "soymutdb-browser" as const;
export const BRIDGE_SOURCE_JBROWSE = "soymutdb-jbrowse" as const;
export const BRIDGE_VERSION = 1 as const;

export type BridgeSource =
    | typeof BRIDGE_SOURCE_BROWSER
    | typeof BRIDGE_SOURCE_JBROWSE;

/** Full message envelope shared by both apps. */
export interface BridgeEnvelope {
    source: BridgeSource;
    version: typeof BRIDGE_VERSION;
    type: string;
    payload?: unknown;
}

/** Portal -> JBrowse: apply/restore a browser session. */
export interface InitPayload {
    assembly?: string;
    locus?: string;
    /** Track IDs to display (comma-separated in URLs). */
    tracks?: string[];
    /** Data release tag, carried through for deep-link fidelity. */
    release?: string;
    /** Opaque session identifier generated by the portal. */
    sessionId?: string;
}

/** JBrowse -> Portal: current viewport changed. */
export interface LocusChangePayload {
    assembly: string;
    locus: string;
    /** Optional extension: active track IDs at the time of the change. */
    tracks?: string[];
}

/** Build the "init" message the portal sends into the iframe. */
export function buildInitMessage(payload: InitPayload): BridgeEnvelope {
    return {
        source: BRIDGE_SOURCE_BROWSER,
        version: BRIDGE_VERSION,
        type: "init",
        payload,
    };
}

/**
 * Validate an incoming message from the JBrowse iframe.
 * @returns the envelope when valid, otherwise null (caller should warn).
 */
export function parseJbrowseMessage(
    event: MessageEvent,
    expectedOrigin: string,
    expectedSourceWindow: Window | null,
): BridgeEnvelope | null {
    if (event.origin !== expectedOrigin) {
        console.warn(
            `[Browser] Ignoring message from unexpected origin: ${event.origin} (expected ${expectedOrigin})`,
        );
        return null;
    }
    if (expectedSourceWindow && event.source !== expectedSourceWindow) {
        console.warn("[Browser] Ignoring message from non-iframe window");
        return null;
    }
    const msg = event.data as Partial<BridgeEnvelope> | null | undefined;
    if (!msg || typeof msg !== "object" || typeof msg.type !== "string") {
        console.warn("[Browser] Ignoring malformed bridge message", event.origin);
        return null;
    }
    if (msg.source !== BRIDGE_SOURCE_JBROWSE || msg.version !== BRIDGE_VERSION) {
        console.warn(
            `[Browser] Ignoring invalid bridge message (source=${String(msg.source)}, version=${String(msg.version)})`,
            event.origin,
        );
        return null;
    }
    return msg as BridgeEnvelope;
}

/** Generate a unique session id for each embedded browser session. */
export function newSessionId(): string {
    try {
        if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
            return crypto.randomUUID();
        }
    } catch {
        // fall through to the timestamp-based id
    }
    return `sess-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}
