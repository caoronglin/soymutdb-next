def test_graph_cli_generates_four_normalized_machine_graphs(tmp_path: Path) -> None:
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "graphs", "--output", str(tmp_path)],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 0, result.stderr
    manifest = json.loads((tmp_path / "manifest.json").read_text(encoding="utf-8"))
    assert manifest["schema_version"] == 1
    assert manifest["status"] == "passed"
    assert set(manifest["graphs"]) == {"compose", "oci", "pnpm", "uv"}

    for graph_name in manifest["graphs"]:
        graph = json.loads(
            (tmp_path / f"{graph_name}.json").read_text(encoding="utf-8")
        )
        assert graph["schema_version"] == 1
        assert graph["ecosystem"] == graph_name
        assert graph["status"] == "passed"
        assert graph["nodes"]
        assert isinstance(graph["edges"], list)
        assert re.fullmatch(r"[0-9a-f]{64}", manifest["graphs"][graph_name]["sha256"])

    compose = json.loads((tmp_path / "compose.json").read_text(encoding="utf-8"))
    assert any(
        edge["from"] == "service:api" and edge["to"] == "service:postgres"
        for edge in compose["edges"]
    )
    oci = json.loads((tmp_path / "oci.json").read_text(encoding="utf-8"))
    assert {"release:api", "release:worker", "release:mcp", "release:jbrowse"}.issubset(
        {node["id"] for node in oci["nodes"]}
    )
    assert any(
        node["id"] == "base-image:ghcr.io/astral-sh/uv:0.5.11"
        for node in oci["nodes"]
    )
    assert any(
        edge["relation"] == "copy_from"
        and edge["to"] == "base-image:ghcr.io/astral-sh/uv:0.5.11"
        for edge in oci["edges"]
    )


def test_missing_audit_executable_is_unavailable_and_fails_closed(
    tmp_path: Path,
) -> None:
    config = tmp_path / "missing-tool.json"
    config.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "checks": [
                    {
                        "name": "missing-tool",
                        "category": "knip",
                        "command": ["soymutdb-tool-that-does-not-exist", "--json"],
                        "report": {
                            "mode": "stdout",
                            "path": "missing-tool.json",
                            "format": "json",
                        },
                    }
                ],
            }
        ),
        encoding="utf-8",
    )

    reports = tmp_path / "reports"
    reports.mkdir()
    (reports / "missing-tool.json").write_text('{"stale": true}\n', encoding="utf-8")
    result = subprocess.run(
        [
            sys.executable,
            str(SCRIPT),
            "audit",
            "--config",
            str(config),
            "--output",
            str(reports),
        ],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 1
    summary = json.loads((reports / "summary.json").read_text(encoding="utf-8"))
    assert summary["status"] == "failed"
    assert summary["checks"] == [
        {
            "category": "knip",
            "exit_code": None,
            "name": "missing-tool",
            "reason": "executable_not_found",
            "report": "missing-tool.json",
            "report_available": False,
            "status": "unavailable",
        }
    ]
    assert not (reports / "missing-tool.json").exists()


def test_nonzero_analyzer_report_is_preserved_and_cannot_pass(tmp_path: Path) -> None:
    config = tmp_path / "finding.json"
    config.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "checks": [
                    {
                        "name": "finding-tool",
                        "category": "circular-dependencies",
                        "command": [
                            sys.executable,
                            "-c",
                            "import json; "
                            "print(json.dumps({'cycles': [['a', 'b']]})); "
                            "raise SystemExit(3)",
                        ],
                        "report": {
                            "mode": "stdout",
                            "path": "finding.json",
                            "format": "json",
                        },
                    }
                ],
            }
        ),
        encoding="utf-8",
    )

    output = tmp_path / "reports"
    result = subprocess.run(
        [
            sys.executable,
            str(SCRIPT),
            "audit",
            "--config",
            str(config),
            "--output",
            str(output),
        ],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 1
    assert json.loads((output / "finding.json").read_text(encoding="utf-8"))["cycles"]
    summary = json.loads((output / "summary.json").read_text(encoding="utf-8"))
    assert summary["checks"][0]["status"] == "failed"
    assert summary["checks"][0]["exit_code"] == 3
    assert summary["checks"][0]["report_available"] is True


def test_governance_policy_covers_every_required_gate_with_pinned_tools() -> None:
    policy = json.loads(CONFIG.read_text(encoding="utf-8"))
    checks = policy["checks"]
    categories = {check["category"] for check in checks}

    assert categories == {
        "circular-dependencies",
        "deptry",
        "duplicate-versions",
        "knip",
        "licenses",
        "vulnerabilities",
    }
    assert sum(check["category"] == "deptry" for check in checks) == 3
    assert sum(check["name"].startswith("pip-audit-") for check in checks) == 3
    assert any(
        check["command"][:3] == ["pnpm", "dedupe", "--check"] for check in checks
    )
    assert any("madge@" in " ".join(check["command"]) for check in checks)
    assert any("knip@" in " ".join(check["command"]) for check in checks)
    assert any(check["name"] == "pnpm-licenses" for check in checks)
    assert any(check["name"].startswith("python-licenses-") for check in checks)
    assert len({check["report"]["path"] for check in checks}) == len(checks)

    for check in checks:
        command = check["command"]
        serialized = " ".join(command)
        assert isinstance(command, list) and command
        assert command[0] not in {"bash", "sh"}
        assert "docker" not in serialized
        if any(
            tool in serialized
            for tool in ("knip@", "madge@", "deptry==", "pip-audit==", "pip-licenses==")
        ):
            assert re.search(r"(?:@|==)\d+\.\d+\.\d+", serialized), serialized


