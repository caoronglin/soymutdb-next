#!/usr/bin/env python3
"""Drive the W6 A/B harness against a real, disposable PostgreSQL.

## Why this file exists

`scripts/db_ab_experiment.py` owns the *method* — the single-factor plan, the
symmetric statistics, the root-level readings, the >=5 alternating rounds and the
isolation refusals. It deliberately imports no database driver, so every rule in
it is testable on a host that has no psql, no Docker and no server. That
separation left one thing missing: nothing ever called `plan_rounds` with a
real `execute`. The framework existed, the driver did not, so the experiment
could be planned but not run.

This file supplies exactly that missing piece and nothing else. It does not
re-implement a measurement, a statistic or a refusal — it wires the existing
harness to a live connection and prints `render_report`'s output.

## The index-visibility problem this has to solve

Both arms run against the same database, so a `CREATE INDEX` in the treatment
arm is visible to the control arm on the very next round: the second control
round would silently measure the index it is supposed to be compared against,
and the two arms would agree for the wrong reason. The control arm therefore
carries the index's *removal* in its `analyse` list, which the harness executes
before every measured reading of that arm. Symmetry is preserved — both arms
still get identical ANALYZE treatment, which is the invariant the audit
required.

## Contract

  * Refuses anything but a `soymutdb_abtest_*` database (H-09). It never drops
    a database, terminates a session, or touches cluster configuration: the
    harness refuses those statements, and this driver only ever issues
    `CREATE DATABASE`, `CREATE TABLE`, `CREATE INDEX IF NOT EXISTS`,
    `DROP INDEX IF EXISTS`, `ANALYZE`, `INSERT` and `SELECT`.
  * The connection parameters come from `SOYMUTDB_TEST_DATABASE_URL` — the
    variable `scripts/with-postgres-service.sh` exports on CNB — but the
    *database name is replaced* with a disposable one. The shared database is
    never a target.
  * Data is generated by `generate_series`, so it is deterministic and the two
    arms are guaranteed to see identical rows. `Comparison.same_rows` proves it
    per run rather than assuming it.

## Usage

    # On CNB the service script provides the connection:
    bash scripts/with-postgres-service.sh -- python3 scripts/run_db_ab_experiment.py

    # Locally, against a throwaway server:
    SOYMUTDB_TEST_DATABASE_URL='postgresql://soymutdb@127.0.0.1:55432/postgres' \
      python3 scripts/run_db_ab_experiment.py --rows 200000

Exit code is 0 when the comparison is decisive or when the treatment is
honestly reported as not decisive; a non-zero code means the run could not be
completed, not that the treatment lost.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import urllib.parse
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from db_ab_experiment import (
    Arm,
    ExperimentPlan,
    IsolationError,
    assert_isolated_target,
    assert_sql_allowed,
    compare,
    normalize_sql,
    plan_rounds,
    render_report,
)

# A statement that returns rows and therefore needs the EXPLAIN wrapper.
# Everything else in this harness is DDL or statistics maintenance.
QUERY_PREFIXES = ("SELECT", "WITH", "VALUES", "TABLE")

DEFAULT_ROWS = 200_000
DEFAULT_ROUNDS = 5


# --------------------------------------------------------------------------------------
# Synchronous facade over asyncpg
# --------------------------------------------------------------------------------------


class SyncConnection:
    """One connection, one event loop, a blocking `run` for the harness's execute.

    The harness calls `execute` synchronously inside its round loop. Creating a
    loop per call would close and reopen the connection every round, so the loop
    and the connection are created once and reused.
    """

    def __init__(self, dsn: str) -> None:
        self._loop = asyncio.new_event_loop()
        self._connection = self._loop.run_until_complete(self._connect(dsn))

    async def _connect(self, dsn: str) -> Any:
        import asyncpg  # imported here so the module stays importable without it

        return await asyncpg.connect(dsn)

    def run(self, sql: str, params: dict[str, Any] | None = None) -> Any:
        """Run a read query.

        asyncpg binds positionally, so the caller's dict must be built in the
        same order as the `$1, $2, ...` placeholders in `sql`. That is the
        harness's contract: it passes `ExperimentPlan.params` through untouched.
        """
        values = list((params or {}).values())
        return self._loop.run_until_complete(
            self._connection.fetch(sql, *values) if values
            else self._connection.fetch(sql)
        )

    def execute_sql(self, sql: str) -> None:
        self._loop.run_until_complete(self._execute_sql(sql))

    async def _execute_sql(self, sql: str) -> None:
        await self._connection.execute(sql)

    def close(self) -> None:
        self._loop.run_until_complete(self._connection.close())
        self._loop.close()


def make_execute(connection: SyncConnection):
    """The `Execute` callable the harness expects.

    Query statements are wrapped in `EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON)`
    and their raw JSON document returned; DDL and ANALYZE run as-is and return
    an empty string, which the harness ignores. Every statement is passed
    through `assert_sql_allowed` first, so a plan that tries to drop a database
    is refused before it reaches the server rather than after.
    """

    def execute(sql: str, params: dict[str, Any]) -> str:
        assert_sql_allowed(sql)
        if normalize_sql(sql).upper().startswith(QUERY_PREFIXES):
            document = connection.run(
                f"EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) {sql}", params
            )
            if not document:
                raise RuntimeError(f"EXPLAIN returned no document for: {normalize_sql(sql)[:120]}")
            value = document[0][0]
            return value if isinstance(value, str) else json.dumps(value)
        connection.execute_sql(sql)
        return ""

    return execute


# --------------------------------------------------------------------------------------
# Disposable target
# --------------------------------------------------------------------------------------


def disposable_dsn(base_url: str, database: str) -> str:
    """Point an existing connection at a disposable database name.

    The credentials and host come from the caller's URL; only the database is
    replaced. The result is run through the harness's own isolation gate, so a
    name that is not `soymutdb_abtest_*` cannot reach a server.
    """
    parsed = urllib.parse.urlsplit(base_url)
    dsn = urllib.parse.urlunsplit(parsed._replace(path=f"/{database}"))
    # `assert_isolated_target` returns the database *name* it accepted, not the
    # DSN, so its result is validated and deliberately discarded here.
    assert_isolated_target(dsn)
    return dsn


def ensure_database(admin_dsn: str, database: str) -> None:
    """Create the disposable database if it is not there yet.

    `CREATE DATABASE` has no IF NOT EXISTS in PostgreSQL, so existence is
    checked first. This is a create, never a drop: the harness forbids
    `DROP DATABASE` and so does this driver.
    """
    assert_isolated_target(f"postgresql://x/{database}")
    connection = SyncConnection(admin_dsn)
    try:
        exists = connection.run(
            "SELECT 1 FROM pg_database WHERE datname = $1", {"name": database}
        )
        if not exists:
            connection.execute_sql(f'CREATE DATABASE "{database}"')
    finally:
        connection.close()


# --------------------------------------------------------------------------------------
# The experiment
# --------------------------------------------------------------------------------------


TABLE = "gene_fact_probe"
INDEX = "ix_gene_fact_probe_gene"


def seed(connection: SyncConnection, rows: int, target_row: int) -> None:
    """Create the table and load it deterministically.

    Exactly one row carries ``target_row`` as its ``gene_id``, which is the row
    the measured lookup probes. Every other row is spread over 40 000 distinct
    ids, so the query is genuinely selective and an index scan can win. The
    distribution is generated, not sampled, so both arms see byte-identical data
    and `Comparison.same_rows` is a real check rather than an assumption.
    """
    connection.execute_sql(f"DROP TABLE IF EXISTS {TABLE};")
    connection.execute_sql(
        f"""
        CREATE TABLE {TABLE} (
            id integer PRIMARY KEY,
            gene_id integer NOT NULL,
            assembly text NOT NULL,
            score numeric(8, 4)
        );
        """
    )
    connection.run(
        f"""
        INSERT INTO {TABLE} (id, gene_id, assembly, score)
        SELECT i,
               CASE WHEN i = $1::int THEN $1::int ELSE ((i * 7919) % 40000) + 1 END,
               CASE WHEN i % 2 = 0 THEN 'v5' ELSE 'v4' END,
               ((i % 1000)::numeric / 10)
        FROM generate_series(1, $2::int) AS i;
        """,
        {"target_row": target_row, "rows": rows},
    )
    connection.execute_sql(f"ANALYZE {TABLE};")


def build_experiment_plan(
    database: str, rounds: int, warmup: int, target_row: int
) -> ExperimentPlan:
    """A single factor: the presence of one index, and nothing else.

    The control arm removes the index in its `analyse` list because the
    treatment arm's index would otherwise remain visible to it. Both arms keep
    the identical `ANALYZE` that the harness requires, so statistics cannot
    become the second variable.
    """
    return ExperimentPlan(
        experiment_id="W6-A-gene-id-lookup-index",
        hypothesis=(
            "A btree index on gene_id makes the public gene lookup selective "
            "enough to beat a sequential scan on a real copy of the fact table."
        ),
        database=database,
        table=TABLE,
        arms=(
            Arm(
                name="control",
                analyse=(f"DROP INDEX IF EXISTS {INDEX};", "ANALYZE;"),
            ),
            Arm(
                name="treatment",
                treatment=(f"CREATE INDEX IF NOT EXISTS {INDEX} ON {TABLE} (gene_id);",),
            ),
        ),
        query_sql=f"SELECT id FROM {TABLE} WHERE gene_id = $1",
        params={"gene_id": target_row},
        rounds=rounds,
        warmup_rounds=warmup,
    )


def run_experiment(
    base_url: str, database: str, rows: int, rounds: int, warmup: int, target_row: int
) -> tuple[ExperimentPlan, Any]:
    ensure_database(base_url, database)
    dsn = disposable_dsn(base_url, database)
    connection = SyncConnection(dsn)
    try:
        seed(connection, rows, target_row)
        plan = build_experiment_plan(database, rounds, warmup, target_row)
        execute = make_execute(connection)
        measurements = plan_rounds(plan, execute)
        return plan, measurements
    finally:
        connection.close()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--url",
        default=os.environ.get("SOYMUTDB_TEST_DATABASE_URL", ""),
        help="connection string; defaults to $SOYMUTDB_TEST_DATABASE_URL",
    )
    parser.add_argument("--database", default="soymutdb_abtest_w6")
    parser.add_argument("--rows", type=int, default=DEFAULT_ROWS)
    parser.add_argument("--rounds", type=int, default=DEFAULT_ROUNDS)
    parser.add_argument("--warmup", type=int, default=1)
    parser.add_argument("--target-row", type=int, default=None)
    args = parser.parse_args(argv)

    if not args.url:
        print(
            "no database URL: pass --url or export SOYMUTDB_TEST_DATABASE_URL "
            "(on CNB, scripts/with-postgres-service.sh exports it)",
            file=sys.stderr,
        )
        return 2

    rows = args.rows
    target = args.target_row if args.target_row is not None else rows

    try:
        plan, measurements = run_experiment(
            args.url, args.database, rows, args.rounds, args.warmup, target
        )
    except IsolationError as error:
        print(f"isolation refusal: {error}", file=sys.stderr)
        return 2

    result = compare(plan, measurements)
    print(render_report(plan, measurements))
    print()

    if not result.is_decisive:
        # Each of these is a different fault, and collapsing them into one
        # message would make a fixture bug look like a harness problem.
        if not result.stable_shape:
            print(
                f"Diagnosis: NOT decisive — a plan shape changed between rounds "
                f"within one arm (control signatures: {result.control.plan_signatures}, "
                f"treatment signatures: {result.treatment.plan_signatures}). The "
                f"candidate or the statistics moved mid-run, so this is not a "
                f"single-factor measurement. Fix the fixture before concluding "
                f"anything.",
                file=sys.stderr,
            )
        elif not result.same_rows:
            print(
                "Diagnosis: NOT decisive — the two arms returned different numbers "
                "of rows, so they are not answering the same question. Check the "
                "fixture before concluding anything.",
                file=sys.stderr,
            )
        else:
            print(
                f"Diagnosis: NOT decisive — shapes were stable and cardinalities "
                f"matched, but the harness requires at least 5 samples per arm and "
                f"got {result.control.samples}/{result.treatment.samples}. Re-run "
                f"with --rounds 5 or more.",
                file=sys.stderr,
            )
        return 1

    if not result.same_plan:
        print(
            f"Measured on `{plan.database}` — a disposable copy. The arms executed "
            f"through different access paths, which is the effect being measured. "
            f"This is a query-level result on a synthetic fixture, not an "
            f"end-to-end improvement, and the ratio moves by tens of percent "
            f"between runs; re-run at least three times and report the spread.",
        )
        return 0

    print(
        f"Measured on `{plan.database}` — a disposable copy. This is a query-level "
        f"result, not an end-to-end one."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
