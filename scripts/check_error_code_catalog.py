#!/usr/bin/env python3
"""Guard the published error-code catalog against silent drift.

``packages/api-client/error-codes.json`` is generated by
``apps/api/app/core/exceptions.py::error_code_catalog()`` and shipped as a
published package artifact (``package.json`` ``files``). The same catalog is
also embedded in ``openapi.json`` as ``x-error-codes``.

``check-contract.sh`` exports the backend OpenAPI document and diffs the
generated TypeScript, but it never regenerates or compares ``error-codes.json``.
A stale, hand-edited, or partially reverted catalog therefore ships with no
gate noticing -- exactly the co-revert blind spot the snapshot guards were
written for, on a file nobody covered.

``error_code_catalog()`` also publishes one code that has no ``SoyMutDBError``
subclass: ``HTTP_ERROR_CODE`` (``http_error``), the generic HTTPException
fallback. The guard reads it from the ``HTTP_ERROR_CODE`` assignment and the
``catalog[HTTP_ERROR_CODE] = ...`` entry rather than hard-coding the value,
so the derived catalog matches what the generator writes. This guard is a
consistency check; the hand-written ``error-codes.golden.json`` lock is what
makes a coordinated rename of the fallback fail.

This guard reads only committed bytes: the exception hierarchy via ``ast``
(no API import, no 3.15 interpreter, no pydantic, no database) and the two
committed JSON artifacts. It derives the catalog the same way the runtime
function does -- every ``SoyMutDBError`` subclass that declares ``error_code``,
with ``inspect.cleandoc`` applied to the class docstring, plus the
``HTTP_ERROR_CODE`` fallback -- and asserts:

* ``error-codes.json`` equals the derived catalog byte-for-key (including the
  description strings, which carry real client-facing semantics);
* ``openapi.json`` ``x-error-codes`` equals the same catalog, so a snapshot
  that was re-exported without the catalog cannot disagree silently;
* the catalog is non-empty and every code is a lowercase snake_case token.

``--self-test`` plants synthetic drift into a temp tree and proves each of
those checks fails on its own, so weakening the guard is caught by the guard.

Usage:
    check_error_code_catalog.py [--root <tree>] [--self-test]
"""
from __future__ import annotations

import argparse
import ast
import inspect
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXCEPTIONS = ROOT / "apps/api/app/core/exceptions.py"
CATALOG = ROOT / "packages/api-client/error-codes.json"
OPENAPI = ROOT / "packages/api-client/openapi.json"

_CODE_RE = re.compile(r"^[a-z][a-z0-9_]*$")

#: The generic HTTPException fallback is published by ``error_code_catalog()``
#: but has no exception class. Its code and description are read from the
#: source assignments below, never hard-coded here.
_FALLBACK_CONST = "HTTP_ERROR_CODE"
#: An independent floor for the one code the consistency check cannot see.
#: Deleting the fallback declaration *and* pruning both artifacts together
#: leaves every ``derived == committed == published`` assertion green, because
#: all three sides moved as one. The published API contract must not lose a
#: client-visible code by a coordinated regenerate, so pin it here instead.
_FALLBACK_CODE = "http_error"
_FALLBACK_DESC = (
    "Generic HTTPException fallback; see x-error-status for the statuses that use it."
)
_FALLBACK_BLOCK = (
    "    catalog[HTTP_ERROR_CODE] = (\n"
    f'        "{_FALLBACK_DESC}"\n'
    "    )\n"
)


def _error_code_value(stmt: ast.stmt) -> ast.expr | None:
    """Return the assigned ``error_code`` expression, for Assign or AnnAssign."""
    if isinstance(stmt, ast.Assign) and any(
        isinstance(target, ast.Name) and target.id == "error_code"
        for target in stmt.targets
    ):
        return stmt.value
    if (
        isinstance(stmt, ast.AnnAssign)
        and isinstance(stmt.target, ast.Name)
        and stmt.target.id == "error_code"
    ):
        return stmt.value
    return None


def _fallback_from_source(tree: ast.Module) -> tuple[str, str] | None:
    """Read the ``HTTP_ERROR_CODE`` value and its published description.

    ``error_code_catalog()`` publishes the generic HTTPException fallback that
    has no ``SoyMutDBError`` subclass:

        catalog[HTTP_ERROR_CODE] = ("...description...")

    Return ``(code, description)`` when both the module-level constant and the
    ``catalog[...] = ...`` assignment are present, else ``None``. Reading both
    matters: a bare leftover constant must not make a dropped catalog entry
    look published.
    """
    const_value: str | None = None
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if (
                    isinstance(target, ast.Name)
                    and target.id == _FALLBACK_CONST
                    and isinstance(node.value, ast.Constant)
                    and isinstance(node.value.value, str)
                ):
                    const_value = node.value.value
    if const_value is None:
        return None

    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign):
            continue
        target = node.targets[0] if len(node.targets) == 1 else None
        if not (
            isinstance(target, ast.Subscript)
            and isinstance(target.value, ast.Name)
            and target.value.id == "catalog"
            and isinstance(target.slice, ast.Name)
            and target.slice.id == _FALLBACK_CONST
        ):
            continue
        value = node.value
        if isinstance(value, ast.Tuple) and len(value.elts) == 1:
            value = value.elts[0]
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            return const_value, value.value
    return None


def _derived_catalog(exceptions_path: Path) -> dict[str, str]:
    """Reproduce ``error_code_catalog()`` from source, without importing the app.

    ``error_code_catalog()`` also publishes ``HTTP_ERROR_CODE`` for the generic
    ``HTTPException`` handler (PR #152), even though no ``SoyMutDBError``
    subclass carries it. Read the constant and its published description from
    the source so the derived catalog stays byte-for-byte with the runtime one.
    """
    tree = ast.parse(exceptions_path.read_text(encoding="utf-8"), filename=str(exceptions_path))
    catalog: dict[str, str] = {}
    fallback: str | None = None
    for node in ast.walk(tree):
        # Module-level ``HTTP_ERROR_CODE = "http_error"``.
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            value = node.value
            if (
                isinstance(value, ast.Constant)
                and isinstance(value.value, str)
                and any(isinstance(t, ast.Name) and t.id == "HTTP_ERROR_CODE" for t in targets)
            ):
                fallback = value.value
        # ``catalog[HTTP_ERROR_CODE] = "description"`` inside error_code_catalog().
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant):
            desc = node.value.value
            if isinstance(desc, str):
                for target in node.targets:
                    if (
                        isinstance(target, ast.Subscript)
                        and isinstance(target.slice, ast.Name)
                        and target.slice.id == "HTTP_ERROR_CODE"
                    ):
                        catalog[fallback or "http_error"] = desc
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            value = _error_code_value(stmt)
            if isinstance(value, ast.Constant) and isinstance(value.value, str):
                # error_code_catalog() uses (cls.__doc__ or "").strip(); Python
                # stores __doc__ already cleandoc'd, so cleandoc here matches.
                doc = inspect.cleandoc(ast.get_docstring(node, clean=False) or "").strip()
                catalog[value.value] = doc
    fallback = _fallback_from_source(tree)
    if fallback is not None:
        code, description = fallback
        catalog[code] = description
    return dict(sorted(catalog.items()))


def check_tree(root: Path) -> list[str]:
    """Return human-readable problems for a tree; empty means the catalog is in sync."""
    problems: list[str] = []
    exceptions_path = root / "apps/api/app/core/exceptions.py"
    catalog_path = root / "packages/api-client/error-codes.json"
    openapi_path = root / "packages/api-client/openapi.json"

    for path in (exceptions_path, catalog_path, openapi_path):
        if not path.is_file():
            problems.append(f"missing required file: {path}")
    if problems:
        return problems

    try:
        derived = _derived_catalog(exceptions_path)
        committed = json.loads(catalog_path.read_text(encoding="utf-8"))
        document = json.loads(openapi_path.read_text(encoding="utf-8"))
    except (SyntaxError, ValueError, OSError) as exc:
        return [f"could not read committed contract bytes: {exc}"]

    if not derived:
        problems.append("no error_code declarations found in the exception hierarchy")
    for code in derived:
        if not _CODE_RE.match(code):
            problems.append(f"error code {code!r} is not lowercase snake_case")

    if committed != derived:
        missing = sorted(set(derived) - set(committed))
        extra = sorted(set(committed) - set(derived))
        changed = sorted(k for k in set(derived) & set(committed) if derived[k] != committed[k])
        problems.append(
            "packages/api-client/error-codes.json does not match error_code_catalog(): "
            f"missing={missing} extra={extra} changed_descriptions={changed}. "
            "Run: pnpm --filter @soymutdb/api-client generate:api-client"
        )

    published = document.get("x-error-codes")
    if published is None:
        problems.append("openapi.json has no x-error-codes extension")
    elif published != derived:
        problems.append(
            "openapi.json x-error-codes does not match error_code_catalog(): "
            "re-export the contract (generate:api-client)"
        )

    # A coordinated source + artifact co-revert keeps all three sides equal and
    # every comparison above green. The published code set is client-visible,
    # so this independent floor is the only assertion that still reddens.
    for label, mapping in (("error-codes.json", committed), ("x-error-codes", published)):
        if isinstance(mapping, dict) and _FALLBACK_CODE not in mapping:
            problems.append(
                f"{label} no longer publishes {_FALLBACK_CODE!r}: a coordinated "
                "source + artifact prune of the generic HTTPException fallback "
                "is a breaking published-contract change, not a regenerate"
            )

    # A guard that compares committed bytes is only meaningful if the bytes
    # can actually be produced and the guard is actually invoked. Pin both
    # wirings so dropping either is a loud failure, not a silent gap.
    for rel, marker, label in (
        ("packages/api-client/scripts/generate-api-client.sh", "--error-codes", "generate-api-client.sh"),
        ("packages/api-client/scripts/check-contract.sh", "check_error_code_catalog.py", "check-contract.sh"),
    ):
        path = root / rel
        if not path.is_file():
            problems.append(f"missing wiring file: {path}")
            continue
        text = path.read_text(encoding="utf-8")
        if marker not in text:
            problems.append(
                f"{label} no longer references {marker!r}; the catalog guard "
                "would be unwired"
            )
    return problems


def self_test() -> int:
    """Prove each invariant fails on a planted drift, and passes on the clean tree."""
    clean = check_tree(ROOT)
    if clean:
        print("SELF-TEST FAIL: the committed tree is already out of sync:", clean, file=sys.stderr)
        return 1

    # The plants run through `_require_changed`, and its verdict is the gate:
    # stubbing it to `return None` turns all of them into no-ops while every
    # case still reports "caught". Self-test the gate first, with a plant that
    # is guaranteed to land and one that is guaranteed not to.
    for planted, expected in (("sentinel-a", "sentinel-b"), ("sentinel-a", "sentinel-a")):
        with tempfile.TemporaryDirectory() as probe_dir:
            probe = Path(probe_dir) / "gate.txt"
            probe.write_text(planted, encoding="utf-8")
            try:
                _require_changed(probe, planted, expected)
            except AssertionError:
                refused = True
            else:
                refused = False
            changed = planted != expected
        if refused == changed:
            print(
                "SELF-TEST FAIL: _require_changed no longer rejects an ablation "
                "that changed nothing; every plant below may be a no-op",
                file=sys.stderr,
            )
            return 1

    cases = {
        "extra code": lambda p: _mutate_json(
            p / "packages/api-client/error-codes.json", lambda d: d.update(phantom_code="not published")
        ),
        "dropped code": lambda p: _mutate_json(
            p / "packages/api-client/error-codes.json",
            lambda d: d.pop("not_found", None),
        ),
        "changed description": lambda p: _mutate_json(
            p / "packages/api-client/error-codes.json",
            lambda d: d.__setitem__("internal_error", "tampered"),
        ),
        "x-error-codes drift": lambda p: _mutate_json(
            p / "packages/api-client/openapi.json",
            lambda d: d["x-error-codes"].update(phantom_code="not published"),
        ),
        "x-error-codes removed": lambda p: _mutate_json(
            p / "packages/api-client/openapi.json", lambda d: d.pop("x-error-codes", None)
        ),
        "source code renamed": lambda p: _mutate_source(
            p / "apps/api/app/core/exceptions.py",
            lambda s: s.replace('error_code = "not_found"', 'error_code = "not_found_tampered"'),
        ),
        "fallback code renamed in source": lambda p: _mutate_source(
            p / "apps/api/app/core/exceptions.py",
            lambda s: s.replace('HTTP_ERROR_CODE = "http_error"', 'HTTP_ERROR_CODE = "http_error_tampered"'),
        ),
        "empty hierarchy": lambda p: (p / "apps/api/app/core/exceptions.py").write_text(
            "# no classes\n", encoding="utf-8"
        ),
        "generator drops error-codes": lambda p: _mutate_wiring(
            p / "packages/api-client/scripts/generate-api-client.sh",
            lambda s: s.replace('  --error-codes "$PKG_DIR/error-codes.json"\n', ""),
        ),
        "contract gate drops guard": lambda p: _mutate_wiring(
            p / "packages/api-client/scripts/check-contract.sh",
            lambda s: s.replace("check_error_code_catalog.py", "unwired_guard.py"),
        ),
        # The fallback has no exception class. A leftover HTTP_ERROR_CODE
        # constant must not stand in for a dropped catalog[HTTP_ERROR_CODE]
        # assignment: `_fallback_from_source` needs both, so the published
        # artifact still containing http_error then disagrees with the source.
        # This is the shape that reddened #136 on main after d09b8dcb shipped
        # the fallback without a subclass.
        "fallback catalog entry dropped": lambda p: _mutate_source(
            p / "apps/api/app/core/exceptions.py",
            lambda s: s.replace(_FALLBACK_BLOCK, ""),
        ),
        # The shape the consistency assertions cannot see: drop the fallback
        # declaration and prune both artifacts together. Every comparison then
        # agrees, and only the independent floor above is left to redden.
        "fallback code pruned from source and both artifacts": lambda p: (
            _mutate_source(
                p / "apps/api/app/core/exceptions.py",
                lambda s: s.replace(_FALLBACK_BLOCK, ""),
            ),
            _mutate_json(
                p / "packages/api-client/error-codes.json",
                lambda d: d.pop(_FALLBACK_CODE, None),
            ),
            _mutate_json(
                p / "packages/api-client/openapi.json",
                lambda d: d["x-error-codes"].pop(_FALLBACK_CODE, None),
            ),
        ),
    }

    failures = 0
    ran = 0
    for name, plant in cases.items():
        with tempfile.TemporaryDirectory() as tmp:
            tree = Path(tmp) / "repo"
            for rel in (
                "apps/api/app/core/exceptions.py",
                "packages/api-client/error-codes.json",
                "packages/api-client/openapi.json",
                "packages/api-client/scripts/generate-api-client.sh",
                "packages/api-client/scripts/check-contract.sh",
            ):
                dest = tree / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(ROOT / rel, dest)
            try:
                plant(tree)
            except AssertionError as exc:
                # A no-op plant is a broken self-test, not a caught defect:
                # report it by name so the layer says which case lost its teeth
                # instead of surfacing a bare traceback.
                print(f"SELF-TEST FAIL: planted {name!r} landed no bytes: {exc}", file=sys.stderr)
                failures += 1
                continue
            problems = check_tree(tree)
            ran += 1
            if not problems:
                print(f"SELF-TEST FAIL: planted {name!r} was NOT caught", file=sys.stderr)
                failures += 1
            else:
                print(f"  ok: planted {name!r} -> caught ({len(problems)} problem(s))")
    if failures:
        return 1
    print(f"error-code catalog self-test passed ({ran} negative cases + clean tree)")
    return 0


def _require_changed(path: Path, before: str, after: str) -> None:
    """Reject an ablation whose needle matched nothing.

    A ``str.replace`` (or a ``dict.pop`` with no default) returns its input
    unchanged when the target is gone. Writing that back leaves a pristine
    tree, so the case would be judged "caught" only by inversion -- green for
    the wrong reason. Failing here turns the rot into a named self-test error.
    """
    if after == before:
        raise AssertionError(f"planted defect did not change {path.name}")


def _mutate_json(path: Path, mutate) -> None:
    before = path.read_text(encoding="utf-8")
    data = json.loads(before)
    # Compare parsed data, not the raw text: the canonical re-dump below is not
    # byte-identical to every committed artifact, so a raw-text check would see
    # a formatting-only difference and accept a plant that changed no values.
    snapshot = json.dumps(data, sort_keys=True)
    mutate(data)
    if json.dumps(data, sort_keys=True) == snapshot:
        raise AssertionError(f"planted defect did not change {path.name}")
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _mutate_wiring(path: Path, mutate) -> None:
    before = path.read_text(encoding="utf-8")
    after = mutate(before)
    _require_changed(path, before, after)
    path.write_text(after, encoding="utf-8")


def _mutate_source(path: Path, mutate) -> None:
    before = path.read_text(encoding="utf-8")
    after = mutate(before)
    _require_changed(path, before, after)
    path.write_text(after, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="tree to check (default: repository)")
    parser.add_argument("--self-test", action="store_true", help="run synthetic drift cases")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()
    problems = check_tree(args.root.resolve())
    if problems:
        print("ERROR CODE CATALOG CONTRACT:", file=sys.stderr)
        for problem in problems:
            print(f"  FAIL: {problem}", file=sys.stderr)
        return 1
    print("OK: error-code catalog matches the exception hierarchy and OpenAPI x-error-codes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
