#!/usr/bin/env python3
"""Pin operation description prose and deprecated flags to a literal fixed point.

Both ``openapi.json`` and ``src/generated/openapi.d.ts`` are exports of
``app.main:app``. Guards that compare them to each other prove
self-consistency, not truth. ``#269`` pinned the operation ``summary`` in
``check_openapi_response_surface.py``; the operation ``description`` prose
(209 operations) and ``deprecated`` flags (2 operations) are still unread.
``openapi-typescript`` renders them into the doc comment above each method in
the generated ``paths`` interface. A coordinated regenerate that rewrites
one on *both* halves moves both artifacts together, so no fixed point sees it:

* ``_OPERATION_ID_DIGEST`` / ``_PARAMETER_DIGEST`` / ``_RESPONSE_SURFACE_DIGEST``
  / ``_OPERATION_SUMMARY_DIGEST`` pin identities, structure and summaries, not
  operation description prose or deprecation flags.
* ``openapi-document-metadata.golden.json`` freezes document-level ``info``
  and the tag catalog, not per-operation ``summary``/``description``.
* ``_BODY_PAIR_DIGEST`` / ``_INLINE_BODY_BASELINE`` see bodies only.
* ``_PINNED_ARTIFACTS`` is a provenance blob id: re-pinning both ids is the
  guard's own documented "one deliberate reviewed action" alongside a
  regenerate, so a co-revert that re-pins them stays green.

Decisive ablation on live bytes (after #269 landed): rewrite one operation
``description`` in the snapshot and in the generated TS ``@description`` line
(byte-preserving, both halves agree), re-pin the two blob ids as that guard
instructs, and every wired OpenAPI guard stays ``rc=0`` with the whole
contracts layer ``SMOKE PASS``. The generated TypeScript doc comment silently
changes -- a client-visible contract break that nothing in the layer pins.

This guard reads committed bytes only (``json`` + ``re`` + stdlib): no Python
3.15, no API import, no wheel, no database, no workspace install. It pins:

* ``_ANNOTATION_DIGEST`` -- a hand-written sha256 over the canonical sorted
  ``(METHOD, path, operationId, description, deprecated)`` tuple set, read
  from nowhere. Exported from both artifacts independently, so a co-revert of
  both halves still changes it;
* ``_EXPECTED_OPERATION_COUNT`` / ``_EXPECTED_DESCRIPTION_COUNT`` /
  ``_EXPECTED_DEPRECATED_COUNT`` -- exact count doors;
* three-way agreement: snapshot per-operation annotations == generated
  ``paths`` doc comments == generated ``operations`` interface symbols. A
  one-sided edit is named by method and path;
* the generated doc comment must render the summary as its first text line
  and the description under ``@description`` (both inline ``/** ... */`` and
  multi-line block shapes), and ``@deprecated`` exactly where the snapshot
  declares it.

The generated doc comment also renders a multi-line description's
continuation prose as indented ``*     ...`` lines (393 lines across 104
operations). ``_ANNOTATION_DIGEST`` pins the snapshot's full description, and
the three-way agreement compares only ``_description_first_line()`` -- so the
snapshot half of a continuation line is frozen while its client-visible
rendering has no fixed point. A regenerate that mangles, drops or relocates
one of those lines (with both provenance blob ids honestly re-pinned) keeps
every other wired guard green and the contracts layer ``SMOKE PASS``. This is
the same genus #297 closed for the generated ``@default`` tags: pin the
generated projection the merged guard did not carry, with a second literal:

* ``_CONTINUATION_DIGEST`` -- a hand-written sha256 over canonical sorted
  ``(METHOD, path, line index, prose)`` rows, read from the committed
  generated bytes, not derived from the snapshot under guard;
* ``_EXPECTED_CONTINUATION_LINES`` / ``_EXPECTED_CONTINUATION_PATHS`` --
  exact count doors. A same-count relocation between two operations moves
  only the digest; both count doors stay silent, which is the positive
  control that the digest is load-bearing.

A legitimate contract change must move the digest in the same commit as the
two artifacts and say why. Re-deriving the digest from the artifacts under
guard would make the pin self-referential, which is the whole failure this
file replaces. ``--self-test`` injects one-sided and coordinated drifts into
copies of the bytes and asserts each is caught; the clean tree must pass.

Usage:
    python3 scripts/check_openapi_operation_annotations.py
    python3 scripts/check_openapi_operation_annotations.py --self-test
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "packages" / "api-client" / "openapi.json"
GENERATED = ROOT / "packages" / "api-client" / "src" / "generated" / "openapi.d.ts"
SMOKE = ROOT / "scripts" / "smoke.sh"
SELF = Path(__file__).name

METHODS = frozenset(
    {"get", "put", "post", "patch", "delete", "options", "head", "trace"}
)

# Reviewed, hand-written fixed point on the whole published annotation surface.
# sha256 of "\n".join(["soymutdb-operation-annotations/v1"] +
#   sorted(f"{method} {path} {operationId} {summary} {description} {deprecated}")).
# Regenerate with _digest() after an intentional contract change and update in
# the same commit, with a reason.
#
# Re-pinned 2026-11-09 with the regenerated snapshot: three `GET /site/*`
# operations (profile, branding, navigation) and five `/admin/data-views`
# operations (sources, list, create, update, delete) were added. Every new
# operation carries a summary; three of them carry a description, which is the
# 209 -> 212 move.
_ANNOTATION_DIGEST = (
    "2b07205d52ff989e117d75de74d556916952b873d642b39d0fec1eb4cc5f31cc"
)
_EXPECTED_OPERATION_COUNT = 276
_EXPECTED_DESCRIPTION_COUNT = 212
_EXPECTED_DEPRECATED_COUNT = 2

# Independent fixed point for the generated continuation prose. sha256 of
# "\n".join(["soymutdb-operation-continuations/v1"] +
#   sorted(f"{method}|{path}|{index}|{prose}")) over every indented ``*    ``
# line in a ``paths`` doc block. Hand-written, NOT derived from the snapshot
# under guard. Regenerate after an intentional, reviewed regenerate and update
# in the same commit as both artifacts, with a reason.
_CONTINUATION_DIGEST = (
    "843549d290930d53af7ee515726735a0d4366e90c0e65ec5c7cc331f77ce6077"
)
_EXPECTED_CONTINUATION_LINES = 393
_EXPECTED_CONTINUATION_PATHS = 104
_CONTINUATION_LINE = re.compile(r"^\*\s{4,}(\S.*)$")

PATH_LINE = re.compile(r'^    "(/[^"]*)": \{$')
OP_REF = re.compile(
    r"^        (get|put|post|patch|delete|options|head|trace): "
    r'operations\["([^"]+)"\];$'
)
OP_DEF = re.compile(r"^    ([A-Za-z_][A-Za-z0-9_]*): \{$", re.MULTILINE)
INLINE_DOC = re.compile(r"^/\*\*\s*(.*?)\s*\*/$")


def _snapshot_rows(document: dict[str, Any]) -> list[tuple[str, str, str, str, str]]:
    """Canonical (METHOD, path, operationId, description, deprecated)."""
    rows: list[tuple[str, str, str, str, str]] = []
    for path, item in document.get("paths", {}).items():
        if not isinstance(item, dict):
            continue
        for method, operation in item.items():
            if method not in METHODS or not isinstance(operation, dict):
                continue
            rows.append(
                (
                    method.upper(),
                    path,
                    str(operation.get("operationId", "")),
                    str(operation.get("description", "")),
                    str(bool(operation.get("deprecated", False))),
                )
            )
    return rows


def _digest(rows: list[tuple[str, str, str, str, str]]) -> str:
    canonical = sorted(rows)
    blob = "\n".join(
        ["soymutdb-operation-annotations/v1"]
        + ["|".join(row) for row in canonical]
    )
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def _generated_doc_blocks(
    generated: str,
) -> dict[tuple[str, str], tuple[str, list[str]]]:
    """(METHOD, path) -> (operations symbol, doc comment text lines).

    ``openapi-typescript`` emits either a one-line ``/** Summary */`` or a
    multi-line block whose first text line is the summary and whose
    ``@description``/``@deprecated`` lines carry the rest. Intervening
    ``?: never;`` rows and the ``parameters`` object do not reset the block.
    """
    out: dict[tuple[str, str], tuple[str, list[str]]] = {}
    in_paths = False
    path: str | None = None
    doc: list[str] = []
    for line in generated.splitlines():
        if line.startswith("export interface paths {"):
            in_paths = True
            continue
        if in_paths and line == "}":
            in_paths = False
            continue
        if not in_paths:
            continue
        match = PATH_LINE.match(line)
        if match:
            path = match.group(1)
            doc = []
            continue
        stripped = line.strip()
        inline = INLINE_DOC.match(stripped)
        if inline:
            doc.append("* " + inline.group(1))
            continue
        if stripped.startswith("*") or stripped.startswith("/**"):
            doc.append(stripped)
            continue
        match = OP_REF.match(line)
        if match and path is not None:
            out[(match.group(1).upper(), path)] = (match.group(2), list(doc))
            doc = []
            continue
        if (
            stripped.endswith("?: never;")
            or stripped.startswith("parameters:")
            or stripped in ("{", "};")
            or stripped.startswith(("query?:", "header?:", "path?:", "cookie?:"))
        ):
            continue
        doc = []
    return out


def _doc_text(lines: list[str]) -> list[str]:
    return [
        line.lstrip("* ").rstrip()
        for line in lines
        if line.startswith("*") and line.lstrip("* ").strip()
    ]


def _generated_symbols(generated: str) -> set[str]:
    """Operation symbols declared in the generated ``operations`` interface."""
    body = generated.split("export interface operations {", 1)
    if len(body) != 2:
        return set()
    return set(OP_DEF.findall(body[1]))


def _generated_annotations(
    document: dict[str, Any], generated: str
) -> dict[tuple[str, str], tuple[str, str, str]]:
    """(METHOD, path) -> (summary, description, deprecated) from TS doc blocks."""
    blocks = _generated_doc_blocks(generated)
    out: dict[tuple[str, str], tuple[str, str, str]] = {}
    for path, item in document.get("paths", {}).items():
        if not isinstance(item, dict):
            continue
        for method, operation in item.items():
            if method not in METHODS or not isinstance(operation, dict):
                continue
            key = (method.upper(), path)
            if key not in blocks:
                continue
            _symbol, lines = blocks[key]
            texts = _doc_text(lines)
            summary = texts[0] if texts else ""
            description = "\n".join(
                text[len("@description ") :]
                for text in texts
                if text.startswith("@description ")
            )
            deprecated = str(any(text.strip() == "@deprecated" for text in texts))
            out[key] = (summary, description, deprecated)
    return out


def _description_first_line(description: str) -> str:
    return description.splitlines()[0] if description else ""


def continuation_rows(generated: str) -> list[tuple[str, str, str, str]]:
    """Canonical ``(METHOD, path, index, prose)`` rows of generated continuation prose.

    ``openapi-typescript`` prints a multi-line description as an
    ``@description <first line>`` marker followed by blank ``*`` separators
    and indented ``*     ...`` prose lines. Those lines are client-visible IDE
    hover text. Read from the committed generated bytes with the same doc-block
    parser the three-way agreement uses, so the row shape cannot drift apart
    from the rest of this guard.
    """
    out: list[tuple[str, str, str, str]] = []
    for (method, path), (_symbol, lines) in _generated_doc_blocks(generated).items():
        for index, line in enumerate(lines):
            match = _CONTINUATION_LINE.match(line)
            if match:
                out.append((method, path, str(index), match.group(1).strip()))
    return out


def _continuation_digest(rows_: list[tuple[str, str, str, str]]) -> str:
    canonical = sorted(f"{m}|{p}|{i}|{text}" for m, p, i, text in rows_)
    blob = "\n".join(["soymutdb-operation-continuations/v1", *canonical])
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def failures(
    document: dict[str, Any],
    generated: str,
    smoke: str,
    digest: str | None = None,
    continuation_digest: str | None = None,
    expected_continuation_lines: int | None = None,
    expected_continuation_paths: int | None = None,
) -> list[str]:
    rows = _snapshot_rows(document)
    found: list[str] = []
    pinned = _ANNOTATION_DIGEST if digest is None else digest
    pinned_continuation = (
        _CONTINUATION_DIGEST if continuation_digest is None else continuation_digest
    )
    pinned_lines = (
        _EXPECTED_CONTINUATION_LINES
        if expected_continuation_lines is None
        else expected_continuation_lines
    )
    pinned_paths = (
        _EXPECTED_CONTINUATION_PATHS
        if expected_continuation_paths is None
        else expected_continuation_paths
    )

    if len(rows) != _EXPECTED_OPERATION_COUNT:
        found.append(
            f"operation count drifted: expected {_EXPECTED_OPERATION_COUNT}, got {len(rows)}"
        )
    described = sum(1 for row in rows if row[3])
    if described != _EXPECTED_DESCRIPTION_COUNT:
        found.append(
            f"description count drifted: expected {_EXPECTED_DESCRIPTION_COUNT}, "
            f"got {described}"
        )
    deprecated = sum(1 for row in rows if row[4] == "True")
    if deprecated != _EXPECTED_DEPRECATED_COUNT:
        found.append(
            f"deprecated count drifted: expected {_EXPECTED_DEPRECATED_COUNT}, "
            f"got {deprecated}"
        )

    actual_digest = _digest(rows)
    if actual_digest != pinned:
        found.append(
            f"published operation annotations drifted: _ANNOTATION_DIGEST pins "
            f"{pinned}, committed bytes hash to {actual_digest}"
        )

    identities = [(row[1], row[2]) for row in rows]
    if len(set(identities)) != len(identities):
        found.append("duplicate (path, operationId) pair in the snapshot")
    operation_ids = [row[2] for row in rows]
    if len(set(operation_ids)) != len(operation_ids):
        found.append("duplicate operationId in the snapshot")

    # Three-way agreement: snapshot annotations, generated doc comments and
    # generated operations symbols must all describe the same operation set.
    blocks = _generated_doc_blocks(generated)
    snapshot_keys = {(row[0], row[1]) for row in rows}
    for key in sorted(snapshot_keys - set(blocks)):
        found.append(f"{key[0]} {key[1]} has no generated paths doc block")
    for key in sorted(set(blocks) - snapshot_keys):
        found.append(f"{key[0]} {key[1]} has a generated doc block but no snapshot operation")

    rendered = _generated_annotations(document, generated)
    for row in sorted(rows):
        method, path, operation_id, description, is_deprecated = row
        key = (method, path)
        if key not in rendered:
            continue
        got_summary, got_description, got_deprecated = rendered[key]
        snapshot_summary = str(
            document["paths"][path][method.lower()].get("summary", "")
        )
        if got_summary != snapshot_summary:
            found.append(
                f"{method} {path} summary disagrees: snapshot "
                f"{snapshot_summary!r}, generated doc comment {got_summary!r}"
            )
        if _description_first_line(description) != _description_first_line(got_description):
            found.append(
                f"{method} {path} description disagrees: snapshot "
                f"{_description_first_line(description)!r}, generated "
                f"{_description_first_line(got_description)!r}"
            )
        if got_deprecated != is_deprecated:
            found.append(
                f"{method} {path} deprecated flag disagrees: snapshot {is_deprecated}, "
                f"generated @deprecated {got_deprecated}"
            )

    symbols = _generated_symbols(generated)
    for row in rows:
        if row[2] and row[2] not in symbols:
            found.append(f"operationId {row[2]!r} has no generated operations symbol")
    for key in sorted(set(blocks)):
        symbol, _lines = blocks[key]
        if symbol not in symbols:
            found.append(f"generated paths reference {symbol!r} is not declared")

    # Generated continuation prose: the snapshot half is pinned by
    # _ANNOTATION_DIGEST, but only the first @description line is compared on
    # the generated half. A regenerate that rewrites, drops or relocates an
    # indented continuation line (with both provenance blob ids re-pinned)
    # otherwise keeps every other guard green. Check against a second
    # independent literal, not against the snapshot, so a co-revert cannot
    # agree its way past this door.
    continuation = continuation_rows(generated)
    if len(continuation) != pinned_lines:
        found.append(
            f"generated continuation line count is {len(continuation)}, "
            f"_EXPECTED_CONTINUATION_LINES pins {pinned_lines}: a published "
            "description continuation was dropped or invented in openapi.d.ts"
        )
    observed_paths = {(m, p) for m, p, _, _ in continuation}
    if len(observed_paths) != pinned_paths:
        found.append(
            f"generated continuation lines span {len(observed_paths)} operations, "
            f"_EXPECTED_CONTINUATION_PATHS pins {pinned_paths}"
        )
    actual_continuation = _continuation_digest(continuation)
    if actual_continuation != pinned_continuation:
        found.append(
            "published generated description continuations drifted: "
            f"_CONTINUATION_DIGEST pins {pinned_continuation} but openapi.d.ts "
            f"derives {actual_continuation}. Re-pin the continuation digest in "
            "the same commit as both artifacts, with a reason."
        )

    # Wiring: the guard's own --self-test must be a standalone call in the
    # contracts layer, or a vacuous guard can never redden the layer. A
    # commented-out line still contains the path but never runs, so require
    # the active command shape from the start of the line.
    marker = "smoke_contracts() {"
    if marker not in smoke:
        found.append("smoke.sh no longer defines smoke_contracts()")
    else:
        body = smoke.split(marker, 1)[1].split("\n}\n", 1)[0]
        active = re.compile(
            r'^[ \t]*"\$\{PYTHON_BIN\}"\s+scripts/'
            + re.escape(SELF)
            + r"\s+--self-test\s*\|\|\s*rc=\$\?",
            re.MULTILINE,
        )
        if not active.search(body):
            found.append(f"{SELF} --self-test is not wired into the contracts layer")
    return found


def check() -> list[str]:
    try:
        document = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
        generated = GENERATED.read_text(encoding="utf-8")
        smoke = SMOKE.read_text(encoding="utf-8")
    except (OSError, ValueError) as exc:
        return [f"could not read committed bytes: {exc}"]
    return failures(document, generated, smoke)


def self_test() -> int:
    document = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    generated = GENERATED.read_text(encoding="utf-8")
    smoke = SMOKE.read_text(encoding="utf-8")
    clean = failures(document, generated, smoke)
    if clean:
        print(f"FAIL self-test: clean tree drifts: {clean}")
        return 1

    cases: list[tuple[str, Any, Any, Any]] = []
    target = "/api/v1/health/live"
    summary = "Liveness"
    description = document["paths"][target]["get"]["description"]

    def plant_snapshot_summary(value: str) -> dict[str, Any]:
        copy_doc = copy.deepcopy(document)
        copy_doc["paths"][target]["get"]["summary"] = value
        return copy_doc, generated, smoke

    def plant_generated_summary(value: str) -> tuple[dict[str, Any], str, str]:
        return document, generated.replace(
            f"         * {summary}\n", f"         * {value}\n", 1
        ), smoke

    def plant_both_descriptions(value: str) -> tuple[dict[str, Any], str, str]:
        """Coordinated description co-revert: #269 cannot see this."""
        copy_doc = copy.deepcopy(document)
        copy_doc["paths"][target]["get"]["description"] = value
        return (
            copy_doc,
            generated.replace(
                f"@description {_description_first_line(description)}",
                f"@description {value}",
                1,
            ),
            smoke,
        )

    cases.append(("one-sided snapshot summary drift", *plant_snapshot_summary("Liveness v2")))
    cases.append(("one-sided generated summary drift", *plant_generated_summary("Liveness v2")))
    cases.append(
        (
            "coordinated description co-revert",
            *plant_both_descriptions("Liveness probe (DRIFTED)"),
        )
    )

    desc_copy = copy.deepcopy(document)
    desc_copy["paths"][target]["get"]["description"] = description + " (changed)"
    cases.append(("one-sided description drift", desc_copy, generated, smoke))

    dep_copy = copy.deepcopy(document)
    dep_copy["paths"][target]["get"]["deprecated"] = True
    cases.append(("one-sided deprecated drift", dep_copy, generated, smoke))

    drop_copy = copy.deepcopy(document)
    del drop_copy["paths"][target]["get"]["summary"]
    cases.append(("dropped summary", drop_copy, generated, smoke))

    rewired = smoke.replace(f"{SELF} --self-test", f"# {SELF} --self-test", 1)
    cases.append(("dropped self-test wire", document, generated, rewired))

    # Generated continuation prose: one-sided rewrite, dropped line, and a
    # same-count relocation that only the digest can name. The snapshot is
    # untouched in all three -- that is the half _ANNOTATION_DIGEST already
    # freezes, and the whole point of pinning the generated projection.
    continuation = "Baseline gates PostgreSQL only; extended also gates the Redis broker."
    rewritten = generated.replace(
        f"*     {continuation}", f"*     {continuation} (REWRITTEN)", 1
    )
    assert rewritten != generated
    cases.append(("one-sided generated continuation rewrite", document, rewritten, smoke))
    dropped = generated.replace(f"*     {continuation}\n", "", 1)
    assert dropped != generated
    cases.append(("dropped generated continuation line", document, dropped, smoke))
    other = "Password strength is validated both client-side and server-side."
    swapped = (
        generated.replace(f"*     {continuation}", "@@A@@", 1)
        .replace(f"*     {other}", "@@B@@", 1)
        .replace("@@A@@", f"*     {other}", 1)
        .replace("@@B@@", f"*     {continuation}", 1)
    )
    assert swapped != generated
    cases.append(("same-count continuation relocation", document, swapped, smoke))

    failed = 0
    for name, doc, gen, smk in cases:
        problems = failures(doc, gen, smk)
        if problems:
            print(f"PASS self-test: {name} is caught -> {len(problems)} failure(s)")
        else:
            failed += 1
            print(f"FAIL self-test: {name} was NOT caught")
    print(f"self-test: {len(cases)} cases, {failed} failure(s)")
    return 1 if failed else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--self-test", action="store_true", help="plant drifts in copies of the bytes"
    )
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    problems = check()
    if problems:
        for problem in problems:
            print(f"FAIL: {problem}")
        return 1
    print(
        "openapi-operation-annotations: OK "
        f"({_EXPECTED_DESCRIPTION_COUNT} descriptions + "
        f"{_EXPECTED_DEPRECATED_COUNT} deprecated flags + "
        f"{_EXPECTED_CONTINUATION_LINES} generated continuation lines pinned)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
